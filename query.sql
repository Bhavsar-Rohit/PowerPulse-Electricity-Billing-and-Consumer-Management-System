-- Update CUST_NAME from CUSTOMER
UPDATE INVOICE
SET CUST_NAME = (
    SELECT C.CUST_NAME
    FROM CUSTOMER C
    WHERE C.CUST_ID = INVOICE.CUST_ID
)
WHERE CUST_NAME IS NULL;

