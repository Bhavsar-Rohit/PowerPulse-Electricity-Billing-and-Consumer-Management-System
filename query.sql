SELECT C.CUST_ID, C.CUST_NAME, A.ADMIN_NAME 
FROM CUSTOMER C
JOIN ADMIN_ROLES AR ON C.CUST_ID = AR.CUST_ID
JOIN ADMIN A ON AR.ADMIN_ID = A.ADMIN_ID
WHERE C.STATE = 'Maharashtra';

SELECT A.ACC_ID, A.ACC_NO, A.CUST_ID, A.CUST_NAME 
