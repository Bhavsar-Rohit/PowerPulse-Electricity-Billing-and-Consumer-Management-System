UPDATE INVOICE
SET TOTAL_AMOUNT = (
    SELECT B.TOTAL_AMOUNT
    FROM BILLING B
    WHERE B.METER_ID = INVOICE.METER_ID
)
WHERE TOTAL_AMOUNT IS NULL;

