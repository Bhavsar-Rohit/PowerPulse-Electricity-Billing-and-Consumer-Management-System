CREATE TABLE CUSTOMER( 
CUST_ID NUMBER(10) PRIMARY KEY NOT NULL, 
CUST_NAME VARCHAR2(25) NOT NULL, 
EMAIL_ID VARCHAR2(25) NOT NULL, 
CONTACT_NO INT, 
ADDRESS VARCHAR2(50), 
STATE VARCHAR2(15), 
CITY VARCHAR2(15), 
PINCODE VARCHAR2(10)  
);


CREATE TABLE ADMIN ( 
  ADMIN_ID NUMBER(10) PRIMARY KEY NOT NULL, 
  ADMIN_NAME VARCHAR2(25) NOT NULL 
);


CREATE TABLE ADMIN_ROLES ( 
ADMIN_ID NUMBER(10), 
CUST_ID NUMBER(10), 
CONSTRAINT ADMIN_ID_FK FOREIGN KEY (ADMIN_ID) REFERENCES 
ADMIN(ADMIN_ID), 
CONSTRAINT CUST_ID_FK FOREIGN KEY (CUST_ID) REFERENCES 
CUSTOMER(CUST_ID) 
);

CREATE TABLE ACCOUNT ( 
ACC_ID NUMBER(10) PRIMARY KEY NOT NULL, 
ACC_NO VARCHAR2(25) NOT NULL, 
CUST_ID NUMBER(10), 
CUST_NAME VARCHAR2(25), 
CONSTRAINT  CUSTOMER_ID_FK 
FOREIGN KEY (CUST_ID) REFERENCES CUSTOMER(CUST_ID) 
);

CREATE TABLE BILLING ( 
METER_ID NUMBER(10) PRIMARY KEY NOT NULL, 
ACC_ID NUMBER(10), 
CUST_ID NUMBER(10), 
PER_MONTH_UNITS NUMBER(6,2), 
AMOUNT_PER_UNIT NUMBER(6,2) DEFAULT 10, 
TOTAL_AMOUNT NUMBER(6,2), 
CONSTRAINT B_ACCOUNT_ID_FK 
FOREIGN KEY (ACC_ID) REFERENCES ACCOUNT(ACC_ID), 
CONSTRAINT B_CUSTOMER_ID_FK 
FOREIGN KEY (CUST_ID) REFERENCES CUSTOMER(CUST_ID) 
);

CREATE TABLE ELEC_BOARD( 
EBOARD_ID NUMBER(10) PRIMARY KEY NOT NULL, 
EBOARD_NAME VARCHAR2(50)); 


CREATE TABLE TARIFF( 
TARIFF_ID NUMBER(10) PRIMARY KEY NOT NULL , 
TARIFF_TYPE VARCHAR2(25)  
);

CREATE TABLE INVOICE ( 
INVOICE_ID NUMBER(10) PRIMARY KEY NOT NULL,  
EBOARD_ID NUMBER(10) NOT NULL, 
ACC_NO VARCHAR2(25), 
TARIFF_ID NUMBER(10), 
READING_DATE date, 
METER_ID NUMBER(10), 
CONSTRAINT E_BOARD_ID_FK 
FOREIGN KEY (EBOARD_ID) REFERENCES ELEC_BOARD(EBOARD_ID), 
CONSTRAINT TARIFF_ID_FK 
FOREIGN KEY (TARIFF_ID) REFERENCES TARIFF(TARIFF_ID), 
CONSTRAINT METER_ID_FK 
FOREIGN KEY (METER_ID) REFERENCES BILLING(METER_ID), 
CONSTRAINT READ_DATE_CHK CHECK (READING_DATE > date('01
01-2023', 'DD-MM-YYYY')) 
);

