SELECT I.INVOICE_ID, I.ACC_NO, I.TARIFF_ID, I.READING_DATE, I.METER_ID 
FROM INVOICE I
LEFT JOIN ACCOUNT A ON I.ACC_NO = A.ACC_NO
LEFT JOIN CUSTOMER C ON A.CUST_ID = C.CUST_ID
WHERE C.STATE = 'Gujarat';

SELECT E.EBOARD_ID, E.EBOARD_NAME, COUNT(I.INVOICE_ID) AS TOTAL_INVOICES 
